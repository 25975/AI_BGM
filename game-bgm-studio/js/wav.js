/* ==========================================================================
 * wav.js — WAV 编码（16/24-bit）+ 循环点元数据（smpl / LIST INFO）
 * 无 DOM 依赖（返回 ArrayBuffer）
 * ========================================================================== */
(function (global) {
  'use strict';

  var GBG = global.GBG = global.GBG || {};

  function writeString(view, offset, str) {
    for (var i = 0; i < str.length; i++) view.setUint8(offset + i, str.charCodeAt(i) & 0xFF);
  }

  function pad2(n) { return n % 2 === 0 ? n : n + 1; }

  function encodeWav(channels, opts) {
    opts = opts || {};
    var sampleRate = opts.sampleRate || 44100;
    var bitDepth = opts.bitDepth || 16;
    var numCh = channels.length;
    var numFrames = channels[0].length;
    var bytesPerSample = bitDepth / 8;
    var blockAlign = numCh * bytesPerSample;
    var dataSize = numFrames * blockAlign;

    // smpl chunk
    var smpl = null;
    if (opts.loop && opts.loop.endFrame > opts.loop.startFrame) {
      var loops = 1;
      var smplSize = 36 + loops * 24;
      var sb = new ArrayBuffer(8 + smplSize);
      var sv = new DataView(sb);
      writeString(sv, 0, 'smpl');
      sv.setUint32(4, smplSize, true);
      sv.setUint32(8, 0, true);           // manufacturer
      sv.setUint32(12, 0, true);          // product
      sv.setUint32(16, Math.round(1e9 / sampleRate), true); // sample period ns
      sv.setUint32(20, 60, true);         // midi unity note
      sv.setUint32(24, 0, true);          // midi pitch fraction
      sv.setUint32(28, 0, true);          // smpte format
      sv.setUint32(32, 0, true);          // smpte offset
      sv.setUint32(36, loops, true);      // num sample loops
      sv.setUint32(40, 0, true);          // sampler data
      var base = 44;
      sv.setUint32(base, 0, true);        // cue point id
      sv.setUint32(base + 4, 0, true);    // type: 0 = forward
      sv.setUint32(base + 8, Math.max(0, opts.loop.startFrame | 0), true);
      sv.setUint32(base + 12, Math.max(0, opts.loop.endFrame | 0), true); // inclusive
      sv.setUint32(base + 16, 0, true);   // fraction
      sv.setUint32(base + 20, 0, true);   // play count 0 = infinite
      smpl = sb;
    }

    // LIST INFO
    var infoTexts = [];
    function utf8Bytes(str) {
      if (typeof TextEncoder !== 'undefined') return Array.prototype.slice.call(new TextEncoder().encode(str));
      var out = [];
      for (var i = 0; i < str.length; i++) {
        var c = str.charCodeAt(i);
        if (c < 0x80) out.push(c);
        else if (c < 0x800) out.push(0xC0 | (c >> 6), 0x80 | (c & 63));
        else if (c < 0xD800 || c >= 0xE000) out.push(0xE0 | (c >> 12), 0x80 | ((c >> 6) & 63), 0x80 | (c & 63));
        else {
          i++;
          var c2 = str.charCodeAt(i);
          var cp = 0x10000 + ((c - 0xD800) << 10) + (c2 - 0xDC00);
          out.push(0xF0 | (cp >> 18), 0x80 | ((cp >> 12) & 63), 0x80 | ((cp >> 6) & 63), 0x80 | (cp & 63));
        }
      }
      return out;
    }
    function addInfo(id, text) {
      if (!text) return;
      var bytes = utf8Bytes(text);
      bytes.push(0);
      infoTexts.push({ id: id, bytes: bytes });
    }
    addInfo('INAM', opts.title || 'LoopForge BGM');
    addInfo('ICMT', opts.comment || 'Generated by LoopForge Game BGM Studio');
    addInfo('ISFT', 'LoopForge Game BGM Studio');
    if (opts.date) addInfo('ICRD', opts.date);
    if (opts.key) addInfo('IKEY', opts.key);

    var infoSize = 4;
    infoTexts.forEach(function (t) { infoSize += 8 + pad2(t.bytes.length); });
    var infoBuf = null;
    if (infoTexts.length) {
      infoBuf = new ArrayBuffer(8 + infoSize);
      var iv = new DataView(infoBuf);
      writeString(iv, 0, 'LIST');
      iv.setUint32(4, infoSize, true);
      writeString(iv, 8, 'INFO');
      var off = 12;
      infoTexts.forEach(function (t) {
        writeString(iv, off, t.id);
        iv.setUint32(off + 4, t.bytes.length, true);
        for (var i = 0; i < t.bytes.length; i++) iv.setUint8(off + 8 + i, t.bytes[i]);
        off += 8 + pad2(t.bytes.length);
      });
    }

    var fmtSize = 16;
    var totalSize = 12 + (8 + fmtSize) + (smpl ? smpl.byteLength : 0) + (infoBuf ? infoBuf.byteLength : 0) + (8 + dataSize);
    var buffer = new ArrayBuffer(totalSize);
    var view = new DataView(buffer);
    var pos = 0;

    writeString(view, pos, 'RIFF'); pos += 4;
    view.setUint32(pos, totalSize - 8, true); pos += 4;
    writeString(view, pos, 'WAVE'); pos += 4;

    // fmt
    writeString(view, pos, 'fmt '); pos += 4;
    view.setUint32(pos, fmtSize, true); pos += 4;
    view.setUint16(pos, 1, true); pos += 2;              // PCM
    view.setUint16(pos, numCh, true); pos += 2;
    view.setUint32(pos, sampleRate, true); pos += 4;
    view.setUint32(pos, sampleRate * blockAlign, true); pos += 4;
    view.setUint16(pos, blockAlign, true); pos += 2;
    view.setUint16(pos, bitDepth, true); pos += 2;

    if (smpl) {
      new Uint8Array(buffer, pos, smpl.byteLength).set(new Uint8Array(smpl));
      pos += smpl.byteLength;
    }
    if (infoBuf) {
      new Uint8Array(buffer, pos, infoBuf.byteLength).set(new Uint8Array(infoBuf));
      pos += infoBuf.byteLength;
    }

    // data
    writeString(view, pos, 'data'); pos += 4;
    view.setUint32(pos, dataSize, true); pos += 4;

    var ch, i, s;
    if (bitDepth === 16) {
      for (i = 0; i < numFrames; i++) {
        for (ch = 0; ch < numCh; ch++) {
          s = Math.max(-1, Math.min(1, channels[ch][i]));
          view.setInt16(pos, s < 0 ? s * 0x8000 : s * 0x7FFF, true);
          pos += 2;
        }
      }
    } else if (bitDepth === 24) {
      for (i = 0; i < numFrames; i++) {
        for (ch = 0; ch < numCh; ch++) {
          s = Math.max(-1, Math.min(1, channels[ch][i]));
          var v = Math.round(s < 0 ? s * 0x800000 : s * 0x7FFFFF);
          if (v < 0) v += 0x1000000;
          view.setUint8(pos, v & 0xFF);
          view.setUint8(pos + 1, (v >> 8) & 0xFF);
          view.setUint8(pos + 2, (v >> 16) & 0xFF);
          pos += 3;
        }
      }
    } else {
      // 32-bit float
      for (i = 0; i < numFrames; i++) {
        for (ch = 0; ch < numCh; ch++) {
          view.setFloat32(pos, channels[ch][i], true);
          pos += 4;
        }
      }
    }
    return buffer;
  }

  /* 把渲染尾巴折叠回开头，生成无缝循环
   * 做法：用循环结束后的自然延续（混响尾音）替换开头一小段，并做等功率交叉淡化。
   * 这样 out[N-1] 与 out[0] 在时间上是相邻采样，接缝连续；同时把尾音的能量带进开头。
   */
  function foldTail(channels, loopSamples, tailSamples, sampleRate) {
    var sr = sampleRate || 44100;
    var fade = Math.min(Math.round(sr * 0.04), Math.floor(loopSamples / 4));
    return channels.map(function (src) {
      var dst = new Float32Array(loopSamples);
      dst.set(src.subarray(0, loopSamples));
      var avail = Math.max(0, src.length - loopSamples);
      var n = Math.min(fade, avail);
      if (n > 8) {
        for (var k = 0; k < n; k++) {
          var t = k / (n - 1);
          // 等功率淡化：开头从「尾音延续」过渡到本体
          var wIn = Math.sqrt(t);
          var wTail = Math.sqrt(1 - t);
          dst[k] = src[k] * wIn + src[loopSamples + k] * wTail;
        }
      }
      return dst;
    });
  }

  function peakOf(channels) {
    var peak = 0;
    for (var ch = 0; ch < channels.length; ch++) {
      var d = channels[ch];
      for (var i = 0; i < d.length; i++) {
        var a = Math.abs(d[i]);
        if (a > peak) peak = a;
      }
    }
    return peak;
  }

  function rmsOf(channels) {
    var sum = 0, n = 0;
    for (var ch = 0; ch < channels.length; ch++) {
      var d = channels[ch];
      for (var i = 0; i < d.length; i++) { sum += d[i] * d[i]; n++; }
    }
    return n ? Math.sqrt(sum / n) : 0;
  }

  function applyGain(channels, gain) {
    if (gain === 1) return channels;
    for (var ch = 0; ch < channels.length; ch++) {
      var d = channels[ch];
      for (var i = 0; i < d.length; i++) d[i] *= gain;
    }
    return channels;
  }

  /* 游戏引擎接入清单
   * opts.offsetBar: 导出文件的起始小节（分轨/循环区间导出时用于换算相对时间）
   */
  function buildManifest(song, opts) {
    opts = opts || {};
    var sr = opts.sampleRate || 44100;
    var bpm = song.meta.bpm;
    var offsetBar = opts.offsetBar || 0;
    var barSec = 4 * 60 / bpm;
    var loopBars = song.loop.endBar - song.loop.startBar;
    var loopStartBar = Math.max(0, song.loop.startBar - offsetBar);
    var startSec = loopStartBar * barSec;
    var loopSec = loopBars * barSec;
    var startFrame = Math.round(startSec * sr);
    var endFrame = Math.round((startSec + loopSec) * sr) - 1;
    return {
      title: song.meta.title,
      style: song.meta.styleName,
      styleId: song.meta.styleId,
      bpm: bpm,
      key: song.meta.keyLabel,
      bars: song.meta.bars,
      export: {
        fromBar: offsetBar + 1,
        toBar: opts.toBar || song.meta.bars,
        note: opts.loopOnly
          ? '仅循环区间（第 ' + (offsetBar + 1) + '–' + (opts.toBar || song.meta.bars) + ' 小节）'
          : (offsetBar ? '音频从第 ' + (offsetBar + 1) + ' 小节开始' : '音频包含整首（含前奏/尾声）')
      },
      meter: '4/4',
      sampleRate: sr,
      bitDepth: opts.bitDepth || 16,
      channels: 2,
      loop: {
        bars: loopBars,
        startBar: song.loop.startBar,
        endBar: song.loop.endBar,
        seconds: +loopSec.toFixed(4),
        startSeconds: +startSec.toFixed(4),
        startSample: startFrame,
        endSample: endFrame,
        frame30: { start: Math.round(startSec * 30), end: Math.round((startSec + loopSec) * 30) },
        frame60: { start: Math.round(startSec * 60), end: Math.round((startSec + loopSec) * 60) }
      },
      sections: song.sections.map(function (s) {
        return {
          name: s.name,
          startBar: s.startBar,
          bars: s.bars,
          startSeconds: +Math.max(0, (s.startBar - offsetBar) * barSec).toFixed(2)
        };
      }),
      layers: song.parts.map(function (p) {
        return { id: p.id, name: p.name, instrument: p.instrument, notes: p.notes.length, intensityGate: p.minIntensity };
      }),
      stems: opts.stems || [],
      seed: song.meta.seed,
      prompt: song.meta.prompt || '',
      generator: 'LoopForge Game BGM Studio',
      createdAt: new Date().toISOString(),
      integration: {
        unity: '导入 WAV 后勾选 Loop，或按 loop.startSample / endSample 设置; MIDI 可导入 Reaper/FL 二次编曲',
        unreal: 'Sound Wave → Looping 开启，设置 Loop Start/End；建议关闭 Compression 预听，最终再调',
        godot: 'AudioStreamWAV 设置 loop_mode = Forward，loop_begin/loop_end 按 sample 填写',
        web: 'AudioBufferSourceNode.loopStart / loopEnd 使用 loop.startSeconds / endSeconds'
      }
    };
  }

  GBG.wav = {
    encode: encodeWav,
    foldTail: foldTail,
    peakOf: peakOf,
    rmsOf: rmsOf,
    applyGain: applyGain,
    buildManifest: buildManifest
  };
})(typeof window !== 'undefined' ? window : globalThis);
